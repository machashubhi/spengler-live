"""
Rink artwork for the widget, from the hockey_rink library (github.com/the-bucketless/hockey_rink).

hockey_rink draws with matplotlib, which a browser can't run. So we take every feature polygon
of its IIHFRink (lines, circles, creases, nets, boards), convert feet to metres and write SVG paths
in Wisehockey's coordinate system: x -30..30, y -15..15, centre ice at 0 (SVG y is flipped).
Colours are CSS classes so the page can theme the rink.

    pip install hockey_rink && python tools/build_rink.py      ->  src/rink.js
"""
import json
import math
import os
import urllib.error  # noqa: F401 - hockey_rink's ice-image fallback needs these modules imported
import urllib.request  # noqa: F401

from hockey_rink import IIHFRink

FT = 0.3048
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "rink.js")


def rdp(pts, eps):
    """Ramer-Douglas-Peucker simplification."""
    if len(pts) < 3:
        return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    dx, dy = x2 - x1, y2 - y1
    norm = math.hypot(dx, dy)
    dmax, idx = 0.0, 0
    for i in range(1, len(pts) - 1):
        px, py = pts[i]
        d = math.hypot(px - x1, py - y1) if norm < 1e-6 else abs(dy * px - dx * py + x2 * y1 - y2 * x1) / norm
        if d > dmax:
            dmax, idx = d, i
    if dmax <= eps:
        return [pts[0], pts[-1]]
    return rdp(pts[: idx + 1], eps)[:-1] + rdp(pts[idx:], eps)


def path(xs, ys, eps=0.02):
    pts = rdp([(float(x) * FT, -float(y) * FT) for x, y in zip(xs, ys)], eps)
    return ("M" + "L".join(f"{x:.2f} {y:.2f}" for x, y in pts) + "Z").replace(".00", "").replace("-0 ", "0 ")


def css(name):
    key = name.rstrip("_0123456789")
    return {"blue_line": "rk-b", "center_circle": "rk-b", "center_dot": "rk-b", "crease": "rk-c", "net": "rk-n"}.get(key, "rk-r")


def main():
    # Neutral zone tuned so the blue lines sit where Wisehockey logs blue-line crossings here (|x| = 7.1-7.2 m).
    rink = IIHFRink(nzone={"length": 45.9})
    feats = []
    for name, f in rink._features.items():
        if type(f).__name__ == "RinkImage" or name.rstrip("_0123456789") in ("nzone", "ozone", "dzone"):
            continue
        xs, ys = f.get_polygon_xy()
        if len(xs):
            feats.append((f.polygon_kw.get("zorder") or 1, css(name), path(xs, ys)))
    feats.sort(key=lambda t: t[0])
    ice = path(*rink._boards.get_xy_for_clip(), eps=0.01)
    boards = path(*rink._boards.get_polygon_xy(), eps=0.01)
    body = "".join(f'<path class="{c}" d="{d}"/>' for _, c, d in feats)
    svg = f'<path fill="__ICE__" d="{ice}"/><g clip-path="__CLIP__">{body}</g><path class="rk-w" d="{boards}"/>'
    with open(OUT, "w") as fh:
        fh.write("// Generated by tools/build_rink.py from hockey_rink's IIHFRink. Do not edit.\n"
                 f"export const RINK_ICE = {json.dumps(ice)};\nexport const RINK_SVG = {json.dumps(svg)};\n")
    print(f"wrote {OUT}: {os.path.getsize(OUT):,} bytes, {len(feats)} features")


if __name__ == "__main__":
    main()
